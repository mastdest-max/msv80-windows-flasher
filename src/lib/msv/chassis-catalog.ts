export function chassisById(id: string): CatalogChassis {
  return CHASSIS.find((item) => item.id === id) ?? CHASSIS[0];
}

export function ecuByKey(chassisId: string, key: string): CatalogEcu {
  const car = chassisById(chassisId);
  for (const group of car.groups) {
    const hit = group.ecus.find((item) => item.key === key);
    if (hit) return hit;
  }
  return car.groups[0].ecus[0];
}

export function firstEcuKey(chassisId: string): string {
  return chassisById(chassisId).groups[0].ecus[0].key;
}
