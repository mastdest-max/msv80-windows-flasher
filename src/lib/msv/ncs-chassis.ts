const SECTION_ORDER = ["Engine", "Transmission", "Chassis", "Safety", "Body", "Climate", "Audio", "Other"] as const;

export function moduleSection(mod: NcsModule): (typeof SECTION_ORDER)[number] {
  const id = mod.id.toUpperCase();
  const sg = mod.sgbd.toUpperCase();
  if (/^(MSV|MSD|MSS|MEV|ME9|ME17|DDE|D6|D7)/.test(sg) || /MOT$|BMO$|DMO$/.test(id)) return "Engine";
  if (id === "EGS" || id === "GWS" || /^(GS|SMG|DKG)/.test(sg)) return "Transmission";
  if (/^(DSC|ABS|ASC|EDC|EHC|AFS|EPS|VGSG|EMF|RDC|ARS|DXC)/.test(sg) || /^(DSC|EDC|EHC|AFS|EPS|EMF|RDC|ARS)/.test(id)) return "Chassis";
  if (/^(MRS|ACSM)/.test(sg) || /^(ABG|ACSM|BABG|ZABG)/.test(id)) return "Safety";
  if (/^IHK/.test(sg) || /^IHK/.test(id)) return "Climate";
  if (/^(CID|CIC|CCC|RAD|AMP|ASK|ULF|TEL|NAV|CDC|MMC|ANT|TVM|CMEDIA|ZBE)/.test(sg) || /^(CID|CIC|RAD|AMP|MASK|MULF|MEDIA|TV|MMC|CAUDI|CAPPL|CGATE|CHOST)/.test(id)) return "Audio";
  if (/^(CAS|FRM|JBBF|KOMB|PDC|SZL|DWA|SD_|EKP|FAS|BFS|PGS|HUD|LDM|FLA|SHD|SINE)/.test(sg) || /^(CAS|FRM|JBBF|KOMBI|KMB|PDC|DWA|EKP|FAS|BFS|PGS|SHD|LDM|FLA|NFRM)/.test(id)) return "Body";
  return "Other";
}

export function modulesBySection(modules: NcsModule[]): Array<{ name: string; modules: NcsModule[] }> {
  return SECTION_ORDER.map((name) => ({
    name,
    modules: modules.filter((item) => moduleSection(item) === name).sort((a, b) => a.sgbd.localeCompare(b.sgbd) || a.id.localeCompare(b.id)),
  })).filter((group) => group.modules.length > 0);
}
